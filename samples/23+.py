def f(a, b):
    if a < b:
        return 0
    if a == b:
        return 1

    return f(a - 3, b) + f(a - 2, b) + f(a - 1, b)


# 36 -> 13 при этом хотя бы одно 28 или 26
print(
    f(36, 26) * f(26, 13)
    + f(36, 28) * f(28, 13)
    - f(36, 28) * f(28, 26) * f(26, 13)
)


# 36 -> 13 при этом хотя бы одно 28 или 26
# но не оба сразу
print(
    f(36, 26) * f(26, 13)
    + f(36, 28) * f(28, 13)
    - 2 * f(36, 28) * f(28, 26) * f(26, 13)
)
